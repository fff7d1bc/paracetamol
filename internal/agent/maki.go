type MakiPlan struct {
	Command         []string
	DefaultProvider string
	DefaultModel    string
	DefaultThinking string
	Endpoint        string
	Init            []byte
	Permissions     []byte
	ProviderConfig  []byte
	Tiers           []byte
	Mode            string
	Remote          bool
	Authenticated   bool
}

func FindRealExecutable(name, wrapper string, environment map[string]string) (string, error) {
	resolvedWrapper, _ := filepath.Abs(wrapper)
	if resolved, err := filepath.EvalSymlinks(resolvedWrapper); err == nil {
		resolvedWrapper = resolved
	}
	for _, directory := range filepath.SplitList(environment["PATH"]) {
		if directory == "" {
			directory = "."
		}
		candidate := filepath.Join(directory, name)
		resolved, err := filepath.EvalSymlinks(candidate)
		if err != nil || resolved == resolvedWrapper {
			continue
		}
		if info, err := os.Stat(resolved); err == nil && info.Mode().IsRegular() && info.Mode().Perm()&0o111 != 0 {
			return resolved, nil
		}
	}
	return "", fmt.Errorf("%s executable not found outside %s's bin directory", name, identity.DisplayName)
}

func MakiMode(arguments []string) string {
	if len(arguments) > 0 && arguments[0] == "--" {
		arguments = arguments[1:]
	}
	if len(arguments) > 0 && contains([]string{"--help", "-h", "--version", "-V", "help", "update", "rollback", "migrate"}, arguments[0]) {
		return "passthrough"
	}
	if len(arguments) > 0 && contains([]string{"auth", "models", "session", "trust", "index", "mcp", "prompt"}, arguments[0]) {
		return "management"
	}
	return "session"
}

func CreateMakiPlan(ctx context.Context, managed catalog.Catalog, projectRoot, gatewayURL string, arguments []string, environment map[string]string, apiKey string) (MakiPlan, error) {
	if len(arguments) > 0 && arguments[0] == "--" {
		arguments = arguments[1:]
	}
	executable, err := FindRealExecutable("maki", filepath.Join(projectRoot, "bin", "maki"), environment)
	if err != nil {
		return MakiPlan{}, err
	}
	mode := MakiMode(arguments)
	if mode == "passthrough" {
		return MakiPlan{Command: append([]string{executable}, arguments...), Mode: mode}, nil
	}
	endpoint, err := config.NormalizeGatewayURL(gatewayURL)
	if err != nil {
		return MakiPlan{}, err
	}
	if apiKey != "" {
		if err := config.ValidateGatewayKey(apiKey); err != nil {
			return MakiPlan{}, err
		}
	}
	var advertised []string
	if mode == "session" {
		advertised, err = gateway.FetchModelIDs(ctx, endpoint, apiKey)
		if err != nil {
			return MakiPlan{}, err
		}
	}
	models, err := AgentModels(managed, advertised)
	if err != nil {
		return MakiPlan{}, err
	}
	provider, model, thinking, err := DefaultModel(models, "Maki")
	if err != nil {
		return MakiPlan{}, err
	}
	sessionID := ""
	if mode == "session" {
		sessionID = newSessionID()
	}
	allowed := make([]string, 0, len(models))
	for _, selected := range models {
		allowed = append(allowed, provider+"/"+selected.ID)
	}
	setup, _ := json.Marshal(map[string]any{
		"always_thinking": "adaptive",
		"provider":        map[string]any{"default_model": provider + "/" + model, "allowed_models": allowed},
		"plugins":         map[string]any{"task": map[string]int{"max_concurrent": 1}},
	})
	init := []byte("-- Generated by Paracetamol. Refreshed on every managed launch.\n" +
		"maki.setup(maki.json.decode(" + luaString(string(setup)) + "))\n")
	init = append(init, makiProvider(identity.DisplayName+" gateway", makiModels(models), sessionID, apiKey)...)
	plan := MakiPlan{
		Command: append([]string{executable}, arguments...), Endpoint: endpoint,
		Remote: remoteEndpoint(endpoint), Authenticated: apiKey != "", Init: init,
		Permissions: makiPermissions(endpoint),
		// A user-selected LAN HTTP origin belongs in providers.toml. Plugin
		// declarations/auth hooks only accept HTTPS or loopback HTTP in Maki.
		ProviderConfig: []byte(fmt.Sprintf("[%s]\nbase_url = %s\n", ProviderID, tomlString(endpoint))),
		Mode:           mode,
	}
	tiers, _ := json.MarshalIndent(map[string]string{"compaction": provider + "/" + model, "weak": provider + "/" + model, "medium": provider + "/" + model, "strong": provider + "/" + model}, "", "  ")
	plan.Tiers = append(tiers, '\n')
	if mode == "session" {
		plan.DefaultProvider, plan.DefaultModel, plan.DefaultThinking = provider, model, thinking
	}
	return plan, nil
}

func makiModels(models []textmodel.Model) []map[string]any {
	result := make([]map[string]any, 0, len(models))
	for _, selected := range models {
		model := map[string]any{"prefixes": []string{selected.ID}, "tier": "medium", "context_window": selected.Context, "max_output_tokens": selected.MaxOutputTokens, "supports_thinking": selected.ReasoningControl != "", "supports_vision": false}
		if selected.ReasoningControl != "" {
			fields := make(map[string]any)
			switch selected.ReasoningControl {
			case "toggle":
				fields["off"] = map[string]any{"chat_template_kwargs": map[string]bool{"enable_thinking": false}}
				fields["adaptive"] = map[string]any{"chat_template_kwargs": map[string]bool{"enable_thinking": true}}
			default:
				field := "reasoning_" + selected.ReasoningControl
				fields["adaptive"] = map[string]string{field: selected.ReasoningDefault}
				for _, level := range selected.ReasoningLevels {
					fields[level] = map[string]string{field: level}
				}
				if selected.ReasoningOff {
					fields["off"] = map[string]string{field: "none"}
				}
			}
			model["thinking_fields"] = fields
			if !selected.ReasoningOff {
				model["requires_thinking"] = true
			}
		}
		result = append(result, model)
	}
	return result
}

func makiProvider(display string, models []map[string]any, sessionID, apiKey string) []byte {
	if models == nil {
		models = []map[string]any{}
	}
	// The OpenAI codec uses the same Chat Completions implementation as
	// Maki's llama.cpp base, but honours this slug's user-selected endpoint.
	// Per-model thinking_fields own reasoning, not a provider-wide dialect.
	info, _ := json.Marshal(map[string]any{"slug": ProviderID, "display_name": display, "codec": "openai", "models": models, "accepts_arbitrary_models": false})
	headers := map[string]string{}
	if apiKey != "" {
		headers["Authorization"] = "Bearer " + apiKey
	}
	if sessionID != "" {
		headers["X-Paracetamol-Session-ID"] = sessionID
	}
	resolved, _ := json.Marshal(map[string]any{"headers": headers})
	return []byte(fmt.Sprintf("local provider = maki.json.decode(%s)\nprovider.auth = function()\n  return maki.json.decode(%s)\nend\n-- The launcher already verified and filtered the gateway inventory.\nprovider.list_models = function() return {} end\nmaki.provider.register(provider)\n", luaString(string(info)), luaString(string(resolved))))
}

func makiPermissions(endpoint string) []byte {
	parsed, _ := url.Parse(endpoint) // CreateMakiPlan has normalized and validated it.
	port := parsed.Port()
	if port == "" {
		port = "443"
		if parsed.Scheme == "http" {
			port = "80"
		}
	}
	return []byte(fmt.Sprintf("min_maki_version = \"0.6.3\"\n\n[permissions]\nnet = true\nnet_hosts = [%s]\nfs_read = false\nfs_write = false\nrun = false\nenv = false\nagent = false\n", tomlString(net.JoinHostPort(parsed.Hostname(), port))))
}

func newSessionID() string {
	var value [16]byte
	if _, err := rand.Read(value[:]); err != nil {
		return ""
	}
	value[6] = value[6]&0x0f | 0x40
	value[8] = value[8]&0x3f | 0x80
	return fmt.Sprintf("%08x-%04x-%04x-%04x-%012x", value[0:4], value[4:6], value[6:8], value[8:10], value[10:16])
}

// Lua long strings preserve JSON escapes verbatim, including Unicode. Pick a
// delimiter absent from the payload rather than interpreting JSON as Lua.
func luaString(value string) string {
	delimiter := "="
	for strings.Contains(value, "]"+delimiter+"]") {
		delimiter += "="
	}
	return "[" + delimiter + "[" + value + "]" + delimiter + "]"
}

func tomlString(value string) string { encoded, _ := json.Marshal(value); return string(encoded) }

func PrepareMakiState(plan MakiPlan, dataRoot string) (SandboxPaths, error) {
	paths, err := PrepareSandboxPaths(dataRoot, "maki")
	if err != nil {
		return SandboxPaths{}, err
	}
	configDir := filepath.Join(paths.Config, "maki")
	providersDir := filepath.Join(configDir, "providers")
	stateDir := filepath.Join(paths.State, "maki")
	for _, path := range []string{configDir, stateDir} {
		if err := secureDirectory(path, true); err != nil {
			return SandboxPaths{}, err
		}
	}
	// Retire only our generated executable provider. Unknown files and links
	// are not migration input and must never be followed or removed.
	legacy := ""
	if _, err := os.Lstat(providersDir); err == nil {
		if err := secureDirectory(providersDir, true); err != nil {
			return SandboxPaths{}, err
		}
		entries, err := os.ReadDir(providersDir)
		if err != nil {
			return SandboxPaths{}, err
		}
		for _, entry := range entries {
			if entry.Name() != ProviderID {
				return SandboxPaths{}, fmt.Errorf("Maki provider directory contains unmanaged entry %s", entry.Name())
			}
		}
		if len(entries) != 0 {
			legacy = filepath.Join(providersDir, ProviderID)
		}
	} else if !os.IsNotExist(err) {
		return SandboxPaths{}, err
	}
	if err := storage.ValidateManagedParent(filepath.Join(configDir, "init.lua"), paths.Root, dataRoot, "Maki state"); err != nil {
		return SandboxPaths{}, err
	}
	if err := writeAtomic(filepath.Join(configDir, "init.lua"), plan.Init, 0o600, false); err != nil {
		return SandboxPaths{}, err
	}
	for name, content := range map[string][]byte{"plugin.toml": plan.Permissions, "providers.toml": plan.ProviderConfig} {
		if err := writeAtomic(filepath.Join(configDir, name), content, 0o600, false); err != nil {
			return SandboxPaths{}, err
		}
	}
	tiers := filepath.Join(stateDir, "model-tiers")
	seed := filepath.Join(stateDir, "paracetamol-tier-seed")
	preserve := false
	if current, err := os.ReadFile(tiers); err == nil {
		previous, _ := os.ReadFile(seed)
		preserve = len(previous) == 0 || string(current) != string(previous)
	}
	if err := writeAtomic(tiers, plan.Tiers, 0o600, preserve); err != nil {
		return SandboxPaths{}, err
	}
	if err := writeAtomic(seed, plan.Tiers, 0o600, false); err != nil {
		return SandboxPaths{}, err
	}
	if legacy != "" {
		// Retire the script only after publishing its replacement. writeAtomic
		// checks file/link safety and removes stale credentials even if the
		// final unlink is interrupted.
		if err := writeAtomic(legacy, []byte("# Provider moved to init.lua\n"), 0o600, false); err != nil {
			return SandboxPaths{}, err
		}
		if err := os.Remove(legacy); err != nil {
			return SandboxPaths{}, err
		}
	}
	return paths, nil
}

func MakiEnvironment(base map[string]string, paths SandboxPaths) (map[string]string, error) {
	legacy := filepath.Join(base["HOME"], ".maki")
	if info, err := os.Stat(legacy); err == nil && info.IsDir() {
		return nil, fmt.Errorf("Maki would ignore private XDG state while %s exists; run the real 'maki migrate xdg' first", legacy)
	}
	result := cloneEnvironment(base)
	// The managed providers.toml must agree with the gateway whose inventory
	// we fetched, even when the host has an unrelated Maki origin override.
	delete(result, strings.ToUpper(strings.ReplaceAll(ProviderID, "-", "_"))+"_BASE_URL")
	result["XDG_CONFIG_HOME"] = paths.Config
	result["XDG_DATA_HOME"] = paths.Data
	result["XDG_STATE_HOME"] = paths.State
	result["XDG_CACHE_HOME"] = paths.Cache
	return result, nil
}
