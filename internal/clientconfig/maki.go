// Package clientconfig renders portable example configuration, not client
// installation, state management, process execution or sandbox policy.
package clientconfig

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"paracetamol/internal/config"
	"paracetamol/internal/identity"
	"paracetamol/internal/textmodel"
)

const RecommendedModel = "unsloth-qwen3.8-flash-next-125b-a6b-ud-q4-k-xl-dflash2"

type MakiFiles struct {
	Providers []byte
	Init      []byte
}

// DefaultModel is a client preference. It must not change the gateway's
// reasoning fallback for ordinary HTTP callers that omit the control.
func DefaultModel(models []textmodel.Model) (textmodel.Model, error) {
	if len(models) == 0 {
		return textmodel.Model{}, fmt.Errorf("gateway exposes no model maintained for coding clients")
	}
	for _, preferred := range []string{RecommendedModel, "unsloth-qwen3.8-flash-next-125b-a6b-ud-q4-k-xl", "unsloth-qwen3.8-27b-ud-q8-k-xl"} {
		for _, model := range models {
			if model.ID == preferred {
				return model, nil
			}
		}
	}
	return models[0], nil
}

func ReasoningDefault(model textmodel.Model) string {
	if model.ID == RecommendedModel || model.ID == "unsloth-qwen3.8-flash-next-125b-a6b-ud-q4-k-xl" {
		for _, level := range textmodel.ReasoningLevels(model) {
			if level == "xhigh" {
				return level
			}
		}
	}
	return textmodel.ReasoningDefault(model)
}

// MakiThinkingFields describes only native model controls, never invented
// token budgets or a provider-wide approximation of different model families.
func MakiThinkingFields(model textmodel.Model) map[string]any {
	fields := make(map[string]any)
	if model.ReasoningControl == "" {
		return fields
	}
	if model.ReasoningControl == "toggle" {
		fields["adaptive"] = map[string]any{"chat_template_kwargs": map[string]any{"enable_thinking": true}}
		if model.ReasoningOff {
			fields["off"] = map[string]any{"chat_template_kwargs": map[string]any{"enable_thinking": false}}
		}
		return fields
	}
	field := "reasoning_" + model.ReasoningControl
	fields["adaptive"] = map[string]any{field: ReasoningDefault(model)}
	for _, level := range model.ReasoningLevels {
		fields[level] = map[string]any{field: level}
	}
	if model.ReasoningOff {
		fields["off"] = map[string]any{field: "none"}
	}
	return fields
}

func Maki(models []textmodel.Model, endpoint string, authenticated bool) (MakiFiles, error) {
	endpoint, err := config.NormalizeGatewayURL(endpoint)
	if err != nil {
		return MakiFiles{}, err
	}
	selected := make([]textmodel.Model, 0, len(models))
	for _, model := range models {
		if model.AgentTools {
			selected = append(selected, model)
		}
	}
	sort.Slice(selected, func(i, j int) bool { return selected[i].ID < selected[j].ID })
	defaultModel, err := DefaultModel(selected)
	if err != nil {
		return MakiFiles{}, err
	}
	provider := identity.StateNamespace
	var output strings.Builder
	fmt.Fprintf(&output, "# Generated by %s. Requires Maki 0.6.3 or newer.\n# Replace this provider block when refreshing, not unrelated providers.\n", identity.DisplayName)
	fmt.Fprintf(&output, "[%s]\ndisplay_name = %s\nprotocol = \"openai\"\nbase_url = %s\ndiscover_models = false\ndefault_model = %s\n", quote(provider), quote(identity.DisplayName+" gateway"), quote(endpoint), quote(provider+"/"+defaultModel.ID))
	fmt.Fprintf(&output, "api_key_env = %s\n", quote(identity.EnvironmentPrefix()+"_API_KEY"))
	if !authenticated {
		output.WriteString("# Maki requires a credential even when this gateway has no authentication.\napi_key = \"paracetamol-local\"\n")
	}
	for _, model := range selected {
		fmt.Fprintf(&output, "\n[[%s.models]]\nid = %s\ntier = \"medium\"\ncontext_window = %d\nmax_output_tokens = %d\nsupports_thinking = %t\nsupports_vision = false\nrequires_thinking = %t\n", quote(provider), quote(model.ID), model.Context, model.MaxOutputTokens, model.ReasoningControl != "", model.ReasoningControl != "" && !model.ReasoningOff)
		fields := MakiThinkingFields(model)
		if len(fields) != 0 {
			fmt.Fprintf(&output, "\n[%s.models.thinking_fields]\n", quote(provider))
			for _, key := range sortedKeys(fields) {
				fmt.Fprintf(&output, "%s = %s\n", quote(key), inlineValue(fields[key]))
			}
		}
	}
	init := "-- Generated by " + identity.DisplayName + ". Maki 0.6.3 or newer.\n" +
		"-- For existing init.lua, merge these fields into its one maki.setup call.\n" +
		"-- Other providers and saved model-tier assignments are left alone.\n" +
		"maki.setup({\n" +
		"    always_thinking = \"adaptive\",\n" +
		"    provider = {\n        default_model = " + luaString(provider+"/"+defaultModel.ID) + ",\n    },\n" +
		"    plugins = {\n        task = { max_concurrent = 2 },\n    },\n" +
		"})\n"
	return MakiFiles{Providers: []byte(output.String()), Init: []byte(init)}, nil
}

// JSON string escaping is also valid for TOML basic strings. Go's %q may
// emit \x escapes, which TOML does not accept.
func quote(value string) string {
	encoded, _ := json.Marshal(value)
	return string(encoded)
}

func sortedKeys(values map[string]any) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

// Values are constructed above, not supplied by the request or an arbitrary
// TOML document. Keep this narrow rather than adding a TOML dependency.
func inlineValue(value any) string {
	switch value := value.(type) {
	case string:
		return quote(value)
	case bool:
		return fmt.Sprint(value)
	case map[string]any:
		var parts []string
		for _, key := range sortedKeys(value) {
			parts = append(parts, quote(key)+" = "+inlineValue(value[key]))
		}
		return "{ " + strings.Join(parts, ", ") + " }"
	default:
		panic("unsupported internally constructed Maki field")
	}
}

func luaString(value string) string {
	separator := "="
	for strings.Contains(value, "]"+separator+"]") {
		separator += "="
	}
	return "[" + separator + "[" + value + "]" + separator + "]"
}
